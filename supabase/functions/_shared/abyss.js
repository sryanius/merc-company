/* ─────────────────────────── 주 단위 ─────────────────────────── */

/** 1주 = 7일 (state.js DAYS_PER_WEEK 와 같은 값. 여기서 import 하면 순환이 된다) */
const DAYS_PER_WEEK = 7;

/**
 * 그 날짜가 속한 **주 번호**. 입장 판정은 요일이 아니라 이 번호로 한다.
 *
 * ★ 탑처럼 "매달 1일"로 못 박으면, 그날 부대가 원정 중이면 한 달치 수입이 통째로 날아간다.
 *   탑은 펫(수집품)이라 괜찮지만 여기는 임금 재원이라 그러면 안 된다.
 *   그래서 요일을 안 가리고 **주당 1회**만 센다.
 */
export function weekIndex(day) {
  const d = Math.max(1, Math.floor(day || 1));
  return Math.floor((d - 1) / DAYS_PER_WEEK);
}
