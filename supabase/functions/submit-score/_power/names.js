const CO_UNIT = ['결사대', '용병단', '부대', '기치'];

/** 받침 여부에 따라 '과'/'와' 선택 */
function josaGwa(word) {
  const ch = word.charCodeAt(word.length - 1);
  if (ch < 0xac00 || ch > 0xd7a3) return '와';
  return (ch - 0xac00) % 28 !== 0 ? '과' : '와';
}

/**
 * 용병단 이름 생성.
 * @param {import('./rng.js').RNG} rng
 * @returns {string}
 */
export function companyName(rng) {
  const r = rng || globalRng;
  const pat = r.int(1, 5);
  if (pat === 1) {
    // 붉은늑대단
    return `${r.pick(CO_ADJ).replace(' ', '')}${r.pick(CO_NOUN)}${r.pick(CO_SUFFIX)}`;
  }
  if (pat === 2) {
    // 심연의 이빨 / 재의 사슬단
    const tail = r.chance(0.45) ? '단' : '';
    return `${r.pick(CO_OF)}의 ${r.pick(CO_NOUN)}${tail}`;
  }
  if (pat === 3) {
    // 검과 장미
    const [a, b] = r.pickMany(CO_NOUN, 2);
    return `${a}${josaGwa(a)} ${b}`;
  }
  if (pat === 4) {
    // 제7결사대
    return `제${r.int(2, 99)}${r.pick(CO_UNIT)}`;
  }
  // 방랑하는 까마귀 용병단
  return `${r.pick(CO_ADJ)} ${r.pick(CO_NOUN)} ${r.pick(CO_UNIT)}`;
}

