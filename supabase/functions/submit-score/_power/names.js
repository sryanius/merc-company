/**
 * 용병 칭호. 등급과 전공(kills)에 따라 격이 올라간다.
 * 반환값은 접두 형태이므로 호출부에서 `${titleFor(m, rng)} ${m.name}` 처럼 붙여 쓴다.
 * @param {{grade?:string, kills?:number}} merc
 * @param {import('./rng.js').RNG} rng
 * @returns {string}
 */
export function titleFor(merc, rng) {
  const r = rng || globalRng;
  const gi = Math.max(0, GRADE_ORDER.indexOf(merc?.grade ?? 'F'));
  let tier = gi >= 5 ? 2 : gi >= 2 ? 1 : 0;
  const kills = merc?.kills || 0;
  if (kills >= 40) tier += 1;
  if (kills >= 120) tier += 1;
  return r.pick(TITLE_TIERS[clamp(tier, 0, TITLE_TIERS.length - 1)]);
}
