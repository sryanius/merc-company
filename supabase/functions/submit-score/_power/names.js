/**
 * 판타지 인명 생성.
 * @param {import('./rng.js').RNG} rng
 * @param {{race?:string}} opts  race: human|elf|dwarf|orc|halfling|beast|undead
 * @returns {string} "이름 성"
 */
export function randomName(rng, { race = 'human' } = {}) {
  const r = rng || globalRng;
  const pool = NAME_POOLS[race] || NAME_POOLS.human;
  const first = r.pick(pool.first);
  const last = r.pick(pool.last);
  return pool.reverse ? `${last} ${first}` : `${first} ${last}`;
}

