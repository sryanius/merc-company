--
-- ★★ 이 파일은 «마이그레이션» 이 아니다. 아무것도 자동으로 하지 않는다.
--   `run_import` 이 잘못된 세이브로 성공했을 때 **되돌리는 유일한 길**을 적어 둔 것이다.
--
-- ★ 왜 있나. 전환 계획은 8단계(이관)를 「되돌릴 수 없는 첫 단계」 로 잡았다.
--   그건 **클라이언트 관점에서만** 참이다 — `db/016:109` 의 자물쇠는
--   `where run_state.imported_at is null` 한 줄이고, `run_state` 에는
--   **트리거도 보호 정책도 없다** (확인함). 그래서 service_role 은 풀 수 있다.
--
--   ⇒ 정확한 위험은 「영영 못 고친다」 가 아니라
--     **「사람이 손으로 개입해야 고친다」** 다. 그 차이가 8단계를 누를 수 있게 만든다.
--
-- ★★ 그래도 함부로 쓰지 마라. 푸는 순간 **다음 이관이 지금 행을 통째로 덮는다.**
--   덮이기 전에 무엇이 들어 있었는지 보고 싶으면 아래 ①을 먼저 돌려라.
