/**
 * 황금 나락 — 상수와 곡선
 * ════════════════════════════════════════════════════════════════════════════
 *
 * 도시 아래로 뚫린 옛 주조장의 수직 갱도. **일주일에 한 번** 내려갈 수 있고,
 * 한 층 내려갈 때마다 골드를 캐낸다. 장비도 펫도 안 나온다 — **오직 골드다.**
 *
 * ─────────────────────────────────────────────────────────────────────────
 * ★ 왜 만들었나
 *
 * "S등급을 얻으려고 저등급 도시에 머무는데 의뢰만으로는 유지비를 못 낸다."
 * 실제로 그렇다. 의뢰 보상은 도시 tier 에 묶여 있는데 임금은 단원의 레벨·등급에만
 * 묶여 있어서, **강해질수록 저티어 도시에 머무는 값이 비싸진다.** 여기에 무한의 탑
 * (매달 최대 125,250G)까지 얹히면 저티어 체류가 사실상 불가능해진다.
 *
 * 그래서 도시 tier 와 **무관한** 골드 수입원을 하나 둔다. 벌이는 도시가 아니라
 * **부대의 힘**이 정한다 — 깊이 내려갈수록 많이 번다.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * ★ 목표 수치 (실측 기준, 이 표가 곡선의 근거다)
 *
 * 주간 필요 골드 = 임금 7일 + 탑 비용(125,250G ÷ 4주):
 *
 *   | 구성                    | 주 임금  | 탑/주   | 주간 필요 |
 *   |-------------------------|---------|--------|----------|
 *   | 정원 21 · Lv55 B · 4차  |  14,994 |  ~5,000 |  ~20,000 |
 *   | 정원 70 · Lv80 A · 4차  |  76,258 |  31,313 |  107,571 |
 *   | 정원 70 · Lv80 S · 4차  | 119,742 |  31,313 |  151,055 |
 *
 * (중간 구성의 탑 비용은 500층 완주가 아니라 200층대 기준으로 잡은 값이다.)
 *
 * 실제로 어디까지 내려가는지는 `tools/abyss.mjs` 로 쟀다 (잠수 4회 평균):
 *
 *   | 부대                     | 도달 심층 | 주간 수입 | 대응 필요치 대비 |
 *   |--------------------------|----------|----------|-----------------|
 *   | Lv30 2차 · 상점템        |     17.8 |   7,460G | (초반은 임금도 적다) |
 *   | Lv55 3차 · 상점템        |     36.3 |  31,810G | 20,000G 의 1.6배  |
 *   | Lv70 3차 · 상점템        |     42.4 |  44,264G |                  |
 *   | Lv80 4차 · 상점템        |     54.3 |  71,950G | 92,318G 의 0.78배 |
 *   | Lv80 4차 · 풀세트        |     80.3 | 157,800G | 151,055G 의 1.04배 |
 *   | 〃 + 저급/중급펫         |     80.4 | 157,300G |                  |
 *
 * 즉 **풀세트를 갖춘 최종 부대가 가장 비싼 정원(70명 Lv80 S)의 주간 지출을 딱 맞춘다.**
 * 상점템 단계에서는 8할쯤이라 의뢰 수입이 아직 필요하다 — 그게 세트를 모을 이유가 된다.
 * **곡선을 만지면 이 표를 다시 재라.** (`node tools/abyss.mjs`)
 *
 * ─────────────────────────────────────────────────────────────────────────
 * ★ 바닥이 없다
 *
 * 탑과 달리 최고 층이 없다. 대신 배율이 **지수로** 오르므로 어느 깊이에서는 반드시 벽에 막힌다.
 * 상한을 숫자로 두지 않는 이유는, 두면 "언젠가 완주하고 나면 수입이 고정된다"가 되기 때문이다.
 * 벌이의 상한은 층수가 아니라 부대의 힘이어야 한다.
 *
 * @module data/abyss
 */

/* ─────────────────────────── 이름표 ─────────────────────────── */

export const ABYSS_NAME = '황금 나락';

/**
 * 안전 상한. **설계상의 끝이 아니라 무한 루프 방지선이다.**
 * 실측 배율이 이 깊이에서 이미 30 을 넘으므로 도달자는 없다.
 */
export const DEPTH_CAP = 300;

/* ─────────────────────────── 보상 ─────────────────────────── */

/**
 * 심층 n 을 지날 때 캐는 골드 = n × 이 값.
 * 누적이 깊이의 제곱으로 늘어난다 — 부대가 두 배 깊이 내려가면 벌이는 네 배가 된다.
 * 그래야 "강해지면 체류 비용을 감당한다"가 성립한다.
 */
export const GOLD_PER_DEPTH = 40;

/** 이 배수의 심층에는 금고가 있다 */
export const VAULT_EVERY = 10;
/** 금고층 보상 배율 */
export const VAULT_MULT = 3;

/** 심층 n 이 금고층인가 */
export function isVaultDepth(depth) {
  return depth > 0 && depth % VAULT_EVERY === 0;
}

/** 심층 n 하나에서 캐는 골드 */
export function depthGold(depth) {
  const d = Math.max(1, Math.round(depth));
  return Math.round(GOLD_PER_DEPTH * d * (isVaultDepth(d) ? VAULT_MULT : 1));
}

/** 1심층부터 n심층까지 전부 캤을 때의 누적 골드 (UI 예상치용) */
export function goldRange(depth) {
  const hi = Math.max(0, Math.min(DEPTH_CAP, Math.round(depth)));
  if (hi < 1) return 0;
  // 등차수열 합 + 금고층 가산분 (루프 없이)
  const base = GOLD_PER_DEPTH * ((1 + hi) * hi) / 2;
  const vaults = Math.floor(hi / VAULT_EVERY);
  const vaultSum = VAULT_EVERY * ((1 + vaults) * vaults) / 2;   // 10+20+...
  return Math.round(base + GOLD_PER_DEPTH * (VAULT_MULT - 1) * vaultSum);
}

/* ─────────────────────────── 난이도 곡선 ───────────────────────────
 * `power` 는 quest.js 의 적 스탯 배율과 같은 축이다 (hp/atk/def/res/spd 전부에 곱한다).
 * 탑(data/tower.js)이 쓰는 축과 같으므로 그쪽 실측 기준점을 그대로 쓸 수 있다:
 *
 *   2.70 = 던전 1웨이브 — Lv80 7인이 장비 없이도 이긴다
 *   4.70 = 풀세트 Lv80 7인 승률 100%
 *   5.90 = 풀세트만으로는 승률 0%
 *
 * 탑은 500층에 걸쳐 완만하게 펼치지만 여기는 **지수**다. 주 1회짜리 짧은 잠수라
 * 200층을 늘어놓을 자리가 없고, 벽이 뚜렷해야 "이번 주는 여기까지"가 읽힌다.
 */

/** 심층 1의 배율 */
export const POWER_BASE = 1.60;
/** 한 심층당 배율 증가율 (복리) */
export const POWER_RATE = 1.0184;

/** 심층 n 의 적 배율 */
export function depthPower(depth) {
  const d = Math.max(1, Math.min(DEPTH_CAP, Math.round(depth)));
  return POWER_BASE * Math.pow(POWER_RATE, d - 1);
}

/**
 * 심층 n 에 설 적의 **레벨**.
 *
 * ★ 탑은 적 레벨을 80 으로 고정한다. 거기는 Lv50 해금에 Lv80 부대를 상정한 컨텐츠라
 *   그래도 됐다. 여기는 다르다 — 임금을 못 내는 건 **중반부터** 시작되는 문제라
 *   Lv35 부대도 몇 심층은 벌어 가야 한다. 레벨을 고정했더니 실측에서
 *   Lv30 2차 부대가 **3심층에서 288G** 를 벌고 끝났다. 컨텐츠가 없는 것과 같다.
 *
 *   45심층에서 80 에 닿고 그 뒤로는 배율만 오른다 (적 레벨 상한이 80 이다).
 */
export const LEVEL_MIN = 28;
export function depthEnemyLevel(depth) {
  const d = Math.max(1, Math.round(depth));
  return Math.max(LEVEL_MIN, Math.min(80, Math.round(LEVEL_MIN + (d - 1) * 1.2)));
}

/** 심층 n 에 설 적의 수 (3~7) */
export function depthEnemyCount(depth) {
  const d = Math.max(1, Math.round(depth));
  if (d < 8) return 3;
  if (d < 20) return 4;
  if (d < 35) return 5;
  if (d < 55) return 6;
  return 7;
}

/**
 * 회복 지점. 이 심층을 **지난 직후** 부대가 전원 만피로 돌아온다.
 * 탑과 같은 이유로 둔다 — 체력 이월만 있으면 후반에 재도전 자체가 불가능해진다.
 */
export const REST_EVERY = 20;
export function isRestDepth(depth) {
  return depth > 0 && depth % REST_EVERY === 0;
}

/* ─────────────────────────── 구역 이름 ─────────────────────────── */

export const ZONES = [
  { upTo: 20, name: '무너진 갱구' },
  { upTo: 50, name: '녹슨 금고층' },
  { upTo: 90, name: '백골의 주조장' },
  { upTo: 140, name: '식은 용해로' },
  { upTo: Infinity, name: '황금의 아가리' },
];

export function zoneOf(depth) {
  const d = Math.max(1, Math.round(depth));
  for (const z of ZONES) if (d <= z.upTo) return z.name;
  return ZONES[ZONES.length - 1].name;
}

